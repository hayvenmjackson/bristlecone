#!/usr/bin/env python3
"""Trains the learned part of the mountain weather model and writes wxmodel-weights.js.

Two pieces:
  1. Quantile regression trees (10th, 50th, 90th percentile) for the error of the physical
     core's temperature, from rows made by build_dataset.js.
  2. The rain/snow logistic, P(snow) = 1 / (1 + exp(a + b*T + c*RH)), from rows that carry an
     observed precipitation type (snow, rain; mix and freezing are left out of this fit).

Validation is leave-one-station-out: every station is predicted by a model that never saw it,
which is the situation on a trail with no station. The new weights are written only if they
beat the physical core alone on that test (unless --force).

Usage:
  python3 tools/weather/train.py rows.csv [--out app/src/main/assets/web/js/wxmodel-weights.js] [--force]
Needs numpy and scikit-learn.
"""
import argparse, csv, datetime, json, math, os, re, sys

import numpy as np
from sklearn.ensemble import GradientBoostingRegressor
from sklearn.linear_model import LogisticRegression

HERE = os.path.dirname(os.path.abspath(__file__))
WEIGHTS = os.path.join(HERE, '../../app/src/main/assets/web/js/wxmodel-weights.js')
QUANTILES = {'p10': 0.1, 'p50': 0.5, 'p90': 0.9}
TREE = dict(n_estimators=150, max_depth=3, learning_rate=0.05, min_samples_leaf=40, subsample=0.8, random_state=7)


def read_weights(path):
    src = open(path, encoding='utf-8').read()
    body = src[src.index('window.BcWxWeights = ') + len('window.BcWxWeights = '):].rstrip().rstrip(';')
    # The file is JavaScript, not JSON: quote bare keys and swap quotes before parsing.
    body = re.sub(r"([{,]\s*)([A-Za-z_][A-Za-z0-9_]*)\s*:", r'\1"\2":', body).replace("'", '"')
    return json.loads(body)


def load(path, features):
    rows = list(csv.DictReader(open(path, encoding='utf-8')))
    if not rows:
        sys.exit('no rows in ' + path)
    header = list(rows[0].keys())
    if len(header) != len(set(header)):
        sys.exit('duplicate column names in ' + path)
    missing = [f for f in features if f not in rows[0]]
    if missing:
        sys.exit('rows lack features ' + ', '.join(missing) + '; rebuild them with build_dataset.js')
    X = np.array([[float(r[f]) for f in features] for r in rows])
    y = np.array([float(r['residual']) for r in rows])
    groups = np.array([r['station'] for r in rows])
    return rows, X, y, groups


def export_tree(est, scale):
    """sklearn regression tree to the app's flat nodes: [feature, threshold, left, right, value]."""
    t = est.tree_
    nodes = []
    for i in range(t.node_count):
        if t.children_left[i] == -1:
            nodes.append([-1, 0, 0, 0, round(float(t.value[i][0][0]) * scale, 5)])
        else:
            nodes.append([int(t.feature[i]), round(float(t.threshold[i]), 6), int(t.children_left[i]), int(t.children_right[i]), 0])
    return nodes


def export_model(m):
    """A fitted GradientBoostingRegressor as a list of trees; the first is its constant start."""
    init = float(np.ravel(m.init_.predict(np.zeros((1, m.n_features_in_))))[0]) if hasattr(m.init_, 'predict') else 0.0
    trees = [[[-1, 0, 0, 0, round(init, 5)]]]
    for est in m.estimators_[:, 0]:
        trees.append(export_tree(est, m.learning_rate))
    return trees


def pinball(y, q, a):
    d = y - q
    return float(np.mean(np.maximum(a * d, (a - 1) * d)))


def leave_one_station_out(X, y, groups):
    stations = sorted(set(groups))
    pred = {k: np.zeros_like(y) for k in QUANTILES}
    for s in stations:
        test = groups == s
        for k, a in QUANTILES.items():
            m = GradientBoostingRegressor(loss='quantile', alpha=a, **TREE).fit(X[~test], y[~test])
            pred[k][test] = m.predict(X[test])
    return pred


def fit_precip(rows):
    lab = [(float(r['est_t']), float(r['est_rh']), 1 if r['type'] == 'snow' else 0) for r in rows if r.get('type') in ('snow', 'rain')]
    if len(lab) < 200 or len({x[2] for x in lab}) < 2:
        return None, len(lab)
    A = np.array([[t, rh] for t, rh, _ in lab]); b = np.array([s for *_, s in lab])
    lr = LogisticRegression(C=10.0, max_iter=1000).fit(A, b)
    # sklearn gives logit P(snow) = w0 + w1*T + w2*RH; the app's form is the negative of that.
    return {'a': round(-float(lr.intercept_[0]), 4), 'b': round(-float(lr.coef_[0][0]), 4), 'c': round(-float(lr.coef_[0][1]), 4)}, len(lab)


def write(path, w):
    feats = json.dumps(w['features'])
    js = ("/* Weights for the mountain weather model (see wxmodel.js and tools/weather/).\n"
          "   Generated by tools/weather/train.py; do not edit by hand.\n\n"
          "   precip: rain/snow logistic, P(snow) = 1 / (1 + exp(a + b*T + c*RH)), T in C, RH in %.\n"
          "   temp:   quantile regression trees for the error of the physical core, at the 10th, 50th\n"
          "           and 90th percentiles, as flat node lists [feature, threshold, left, right, value]. */\n"
          "window.BcWxWeights = {\n"
          "  version: " + json.dumps(w['version']) + ",\n"
          "  trained: " + json.dumps(w['trained']) + ",\n"
          "  features: " + feats + ",\n"
          "  precip: " + json.dumps(w['precip']) + ",\n"
          "  temp: " + json.dumps(w['temp'], separators=(',', ':')) + "\n"
          "};\n")
    open(path, 'w', encoding='utf-8').write(js)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('rows')
    ap.add_argument('--out', default=WEIGHTS)
    ap.add_argument('--force', action='store_true')
    args = ap.parse_args()

    w = read_weights(WEIGHTS)
    rows, X, y, groups = load(args.rows, w['features'])
    n_st = len(set(groups))
    print(f'{len(y)} rows from {n_st} stations')
    if n_st < 5:
        sys.exit('need at least 5 stations for a meaningful leave-one-station-out test')

    pred = leave_one_station_out(X, y, groups)
    core_mae = float(np.mean(np.abs(y)))
    new_mae = float(np.mean(np.abs(y - pred['p50'])))
    cover = float(np.mean((y >= pred['p10']) & (y <= pred['p90'])))
    print(f'temperature error, held-out stations: core alone {core_mae:.2f} C, with correction {new_mae:.2f} C')
    print(f'10th to 90th percentile band holds {cover:.0%} of held-out readings (target 80%)')
    for k, a in QUANTILES.items():
        print(f'  pinball loss {k}: {pinball(y, pred[k], a):.3f}')

    precip, n_lab = fit_precip(rows)
    print(f'rain/snow fit: {n_lab} labeled rows' + ('' if precip else ' (too few, keeping current coefficients)'))

    if new_mae >= core_mae and not args.force:
        sys.exit('correction does not beat the core on held-out stations; weights not written')

    out = dict(w)
    out['temp'] = {k: export_model(GradientBoostingRegressor(loss='quantile', alpha=a, **TREE).fit(X, y)) for k, a in QUANTILES.items()}
    if precip:
        out['precip'] = precip
    stamp = datetime.date.today().isoformat()
    out['version'] = 'gbq-' + stamp
    out['trained'] = {'date': stamp, 'rows': int(len(y)), 'stations': n_st, 'heldOutMaeC': round(new_mae, 3), 'coreMaeC': round(core_mae, 3), 'band80': round(cover, 3)}
    write(args.out, out)
    print('wrote ' + args.out)


if __name__ == '__main__':
    main()
